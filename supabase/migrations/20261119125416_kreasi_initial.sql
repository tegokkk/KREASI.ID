-- Better Auth 1.7.26 + KREASI.ID. __KREASI_SCHEMA__ is replaced with a validated identifier.
CREATE SCHEMA IF NOT EXISTS "__KREASI_SCHEMA__";
REVOKE ALL ON SCHEMA "__KREASI_SCHEMA__" FROM PUBLIC;

CREATE TABLE "__KREASI_SCHEMA__"."user" (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
  "emailVerified" BOOLEAN NOT NULL DEFAULT false, image TEXT,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(), "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','superadmin')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  "reviewNote" TEXT NOT NULL DEFAULT ''
);
CREATE TABLE "__KREASI_SCHEMA__"."session" (
  id TEXT PRIMARY KEY, "expiresAt" TIMESTAMPTZ NOT NULL, token TEXT NOT NULL UNIQUE,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(), "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "ipAddress" TEXT, "userAgent" TEXT, "userId" TEXT NOT NULL REFERENCES "__KREASI_SCHEMA__"."user"(id) ON DELETE CASCADE
);
CREATE TABLE "__KREASI_SCHEMA__"."account" (
  id TEXT PRIMARY KEY, "accountId" TEXT NOT NULL, "providerId" TEXT NOT NULL,
  "userId" TEXT NOT NULL REFERENCES "__KREASI_SCHEMA__"."user"(id) ON DELETE CASCADE,
  "accessToken" TEXT, "refreshToken" TEXT, "idToken" TEXT,
  "accessTokenExpiresAt" TIMESTAMPTZ, "refreshTokenExpiresAt" TIMESTAMPTZ, scope TEXT, password TEXT,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(), "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE "__KREASI_SCHEMA__"."verification" (
  id TEXT PRIMARY KEY, identifier TEXT NOT NULL, value TEXT NOT NULL, "expiresAt" TIMESTAMPTZ NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(), "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE "__KREASI_SCHEMA__"."rateLimit" (
  id TEXT PRIMARY KEY, key TEXT NOT NULL UNIQUE, count INTEGER NOT NULL, "lastRequest" BIGINT NOT NULL
);
CREATE TABLE "__KREASI_SCHEMA__".account_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES "__KREASI_SCHEMA__"."user"(id),
  admin_id TEXT NOT NULL REFERENCES "__KREASI_SCHEMA__"."user"(id),
  decision TEXT NOT NULL CHECK(decision IN ('approved','rejected')), note TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE "__KREASI_SCHEMA__".user_journey_progress (
  user_id TEXT NOT NULL REFERENCES "__KREASI_SCHEMA__"."user"(id) ON DELETE CASCADE,
  step_id TEXT NOT NULL CHECK(step_id IN ('self-check','kenali-potensi','mengembangkan-potensi','kuis','refleksi','action-plan')),
  status TEXT NOT NULL CHECK(status IN ('completed','skipped')), completed_at TEXT, updated_at TEXT NOT NULL,
  PRIMARY KEY(user_id, step_id), CHECK(status <> 'completed' OR completed_at IS NOT NULL)
);
CREATE INDEX "session_userId_idx" ON "__KREASI_SCHEMA__"."session"("userId");
CREATE INDEX "account_userId_idx" ON "__KREASI_SCHEMA__"."account"("userId");
CREATE INDEX verification_identifier_idx ON "__KREASI_SCHEMA__"."verification"(identifier);
CREATE INDEX account_reviews_user_idx ON "__KREASI_SCHEMA__".account_reviews(user_id);
CREATE INDEX account_reviews_admin_idx ON "__KREASI_SCHEMA__".account_reviews(admin_id);
CREATE INDEX user_status_created_idx ON "__KREASI_SCHEMA__"."user"(role, status, "createdAt" DESC, id DESC);

-- Backend connections own these private tables; browser/Data API roles have no access.
ALTER TABLE "__KREASI_SCHEMA__"."user" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "__KREASI_SCHEMA__"."session" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "__KREASI_SCHEMA__"."account" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "__KREASI_SCHEMA__"."verification" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "__KREASI_SCHEMA__"."rateLimit" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "__KREASI_SCHEMA__".account_reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE "__KREASI_SCHEMA__".user_journey_progress ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA "__KREASI_SCHEMA__" FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA "__KREASI_SCHEMA__" FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON SCHEMA "__KREASI_SCHEMA__" FROM anon;
    REVOKE ALL ON ALL TABLES IN SCHEMA "__KREASI_SCHEMA__" FROM anon;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA "__KREASI_SCHEMA__" FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON SCHEMA "__KREASI_SCHEMA__" FROM authenticated;
    REVOKE ALL ON ALL TABLES IN SCHEMA "__KREASI_SCHEMA__" FROM authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA "__KREASI_SCHEMA__" FROM authenticated;
  END IF;
END $$;
